import numpy as np
from units import dB
import pipewire_utils

RATIO_TO_K = {"amplitude": 2, "power": 1}

def db_to_lin(db: dB | np.ndarray, ratio="amplitude", reference=1) -> float | np.ndarray:
    k = RATIO_TO_K[ratio]
    return 10 ** (db / (10*k)) * reference


def lin_to_db(lin: float | np.ndarray, ratio="amplitude", reference=1) -> dB | np.ndarray:
    k = RATIO_TO_K[ratio]
    return k * 10 * np.log10(lin / reference)


class SingletonMeta(type):
    _instances = {}

    def __call__(cls, *args, **kwargs):
        if cls not in cls._instances:
            instance = super().__call__(*args, **kwargs)
            cls._instances[cls] = instance
        return cls._instances[cls]


def generate_tilted_noise(num_samples, db_per_octave, fs=44100):
    """
    generated by gemini
    Generate Gaussian noise with a custom spectral tilt in dB per octave.

    :param num_samples: Total number of audio/signal samples
    :param db_per_octave: Desired slope in dB per octave (e.g., -3 for pink, -6 for brown)
    :param fs: Sampling frequency in Hz
    :return: 1D numpy array of time-domain noise samples
    """
    # 1. Generate white noise in the time domain
    white_noise = np.random.normal(0, 1, num_samples)

    # 2. Transform to frequency domain
    f_spectrum = np.fft.rfft(white_noise)

    # 3. Create frequency array corresponding to rfft bins
    freqs = np.fft.rfftfreq(num_samples, d=1/fs)

    # Avoid division by zero at 0 Hz (DC component)
    freqs[0] = freqs[1]

    # 4. Calculate exponent alpha from dB per octave
    # Power scales as f^alpha, so amplitude scales as f^(alpha / 2)
    alpha = db_per_octave / (10.0 * np.log10(2.0))
    amplitude_multiplier = freqs ** (alpha / 2.0)

    # Apply the spectral filter
    filtered_spectrum = f_spectrum * amplitude_multiplier

    # 5. Transform back to the time domain
    tilted_noise = np.fft.irfft(filtered_spectrum, n=num_samples)
    tilted_noise = tilted_noise.astype(np.float32)

    # Normalize to unit standard deviation
    tilted_noise /= np.max(np.abs(tilted_noise)) * 2

    return tilted_noise


def connect_program_nodes_to_patchbay(jack_client):
    sinks = pipewire_utils.get_sinks()
    old_default_sink = next(filter(lambda sink: sink.is_default, sinks))

    # Create new pass-through sink
    jack_client_name = jack_client.client.name
    jack_client_node_id = pipewire_utils.get_node_id_by_node_name(jack_client_name)
    print(jack_client_node_id)
    pipewire_utils.create_null_audio_sink(f"{jack_client_name} Sink")

    sinks = pipewire_utils.get_sinks()
    new_default_sink = next(filter(lambda sink: sink.node_name == f"{jack_client_name} Sink", sinks))

    # set new default sink
    pipewire_utils.wireplumber_set_default(new_default_sink.id)

    pipewire_utils.connect_nodes(new_default_sink.id, jack_client_node_id)
    pipewire_utils.connect_nodes(jack_client_node_id, old_default_sink.id)

    return (old_default_sink, new_default_sink)
